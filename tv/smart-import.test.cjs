const {JSDOM}=require('jsdom');
const fs=require('fs'),assert=require('node:assert/strict');
const html=fs.readFileSync(process.argv[2]||'android-source/app/src/main/assets/index.html','utf8');
const dom=new JSDOM(html,{url:'https://sions.test',runScripts:'outside-only'});
const w=dom.window,d=w.document;
w.scrollTo=()=>{};
w.SionsAndroid={smartImport:raw=>{w.__selected=JSON.parse(raw);},backupExport:raw=>{w.__backup=raw;}};
for(const script of d.querySelectorAll('script:not([src])'))if(script.type!=='application/json')w.eval(script.textContent);
const more=d.getElementById('moreScreen');
assert(more,'The More screen exists');
const oldBackup=d.createElement('div');
oldBackup.id='sions-backup';oldBackup.className='panel';
const save=d.createElement('button');save.className='primary';save.textContent='Spara allt som ZIP';
save.onclick=()=>{w.__saved=true;};oldBackup.appendChild(save);more.appendChild(oldBackup);
const launch=d.createElement('button');launch.textContent='♫ Ljudbibliotek · importera musik';
launch.onclick=()=>{w.__library=true;};more.appendChild(launch);
w.eval(fs.readFileSync('tv/smart-import.js','utf8'));
d.dispatchEvent(new w.Event('DOMContentLoaded'));
const panel=d.getElementById('sions-smart-import');
assert(panel,'One unified import panel');
assert(d.querySelector('.panel #importBtn').closest('.panel').classList.contains('ssi-legacy-hidden'),'Old JSON import hidden, not removed');
assert(oldBackup.classList.contains('ssi-legacy-hidden'),'Old backup controls hidden but working');
assert(launch.classList.contains('ssi-legacy-hidden'),'Old music import button hidden');
const importer=panel.querySelector('#sions-smart-import-open');
importer.click();
assert(Array.isArray(w.__selected),'Smart importer uses native bridge');
const backup=panel.querySelector('#sions-smart-backup-export');backup.click();
assert(w.__saved,'Only visible backup button delegates to original full ZIP export');
const help=panel.querySelector('.ssi-help');help.click();
assert(!panel.querySelector('#sions-smart-help').hidden,'Question mark opens format help');
assert(panel.textContent.includes('Opus')&&panel.textContent.includes('MusicXML')&&panel.textContent.includes('komplett säkerhetskopia'),'Help explains formats and complete ZIP');
assert(panel.textContent.includes('Säkerhetskopiera allt')&&panel.textContent.includes('Importera filer eller ZIP'),'Only two primary actions');
panel.querySelector('#sions-open-library').click();assert(w.__library,'Audio library still accessible');
console.log('PASS: one intelligent import, one complete backup, help, legacy functions preserved');
dom.window.close();
